import { bindDebugListeners } from "./api/client.js";
import { bindAuth, initAuth, showLoginGate } from "./controllers/auth.js";
import { bindCsv } from "./controllers/csv.js";
import { bindDialer } from "./controllers/dialer.js";
import { bindKeyboard } from "./controllers/keyboard.js";
import { bindNavigation } from "./controllers/navigation.js";
import { bindOutcomes } from "./controllers/outcomes.js";
import { bindSettings } from "./controllers/settings.js";
import { arcadeSensory, startArcade } from "./features/arcade/controller.js";
import { bindVoice } from "./features/voice/device.js";
import { startPolling } from "./store/poller.js";
import { byId, setText } from "./utils/format.js";
import { bindCallMonitor } from "./views/call-monitor.js";
import { bindCallerPool } from "./views/caller-pool.js";
import { bindDialogs } from "./views/dialogs.js";
import { renderTable } from "./views/prospects-table.js";
import { bindSessionGoal } from "./views/session-goal.js";

bindDebugListeners();
startArcade();
bindNavigation();
bindDialogs();
bindSettings();
bindCsv();
byId("searchInput").addEventListener("input", renderTable);
byId("statusFilter").addEventListener("change", renderTable);
bindCallerPool();
bindCallMonitor();
bindSessionGoal();
bindDialer();
bindKeyboard();
bindOutcomes();
byId("arcadeEnabledInput").addEventListener("change", (event) => arcadeSensory.updatePreferences({ enabled: event.target.checked }));
byId("arcadeReelsInput").addEventListener("change", (event) => arcadeSensory.updatePreferences({ reels: event.target.checked }));
byId("arcadeSoundInput").addEventListener("change", (event) => arcadeSensory.updatePreferences({ sound: event.target.checked }));
byId("arcadeVolumeInput").addEventListener("input", (event) => {
  setText("arcadeVolumeValue", `${event.target.value}%`);
  arcadeSensory.updatePreferences({ volume: Number(event.target.value) });
});
byId("arcadeShakeInput").addEventListener("change", (event) => arcadeSensory.updatePreferences({ shake: event.target.checked }));
byId("arcadeHapticsInput").addEventListener("change", (event) => arcadeSensory.updatePreferences({ haptics: event.target.checked }));
bindVoice();
bindAuth();
initAuth().catch((error) => showLoginGate(error.message || "Could not start sign-in."));
startPolling();
